import { Queue } from './engine/queue.js';
import { MinHeap } from './engine/heap.js';
import { bfs, bfsPath } from './engine/bfs.js';
import { buildShift, newRun, SHIFTS } from './engine/sim.js';
import { runAlgo, traceAlgo } from './engine/algo.js';
import { average, verdict, losses } from './engine/score.js';
export function runChecks() {
  const r = [];
  const t = (n, f) => { try { r.push([n, !!f()]); } catch { r.push([n, false]); } };
  t('Queue keeps first-in first-out order', () => { const q = new Queue(); [1, 2, 3].forEach((x) => q.push(x)); return q.shift() === 1 && q.shift() === 2; });
  t('Queue reports its size', () => { const q = new Queue(); q.push(1); q.push(2); q.shift(); return q.size === 1; });
  t('Heap pops in sorted order', () => { const h = new MinHeap(); [5, 1, 4, 2, 3].forEach((x) => h.push(x)); return [1, 2, 3, 4, 5].every((x) => h.pop() === x); });
  t('Heap returns undefined when empty', () => new MinHeap().pop() === undefined);
  t('Heap handles interleaved push and pop', () => { const h = new MinHeap(); h.push(3); h.push(1); const a = h.pop(); h.push(0); return a === 1 && h.pop() === 0; });
  t('BFS start distance is 0', () => bfs(new Set(), 3, 3, 0, 0)[0] === 0);
  t('BFS neighbour distance is 1', () => bfs(new Set(), 3, 3, 0, 0)[1] === 1);
  t('BFS far corner distance is 4', () => bfs(new Set(), 3, 3, 0, 0)[8] === 4);
  t('BFS marks blocked cells unreachable', () => bfs(new Set(['1,0', '0,1']), 3, 3, 0, 0)[8] === -1);
  const sh = Object.keys(SHIFTS).map(buildShift);
  t('Lunch has 12 orders', () => sh[0].orders.length === 12);
  t('Rain has 14 orders', () => sh[1].orders.length === 14);
  t('Night has 16 orders', () => sh[2].orders.length === 16);
  t('Three shifts total 42 orders', () => sh.reduce((s, x) => s + x.orders.length, 0) === 42);
  t('Rain closes the bridge at row 2', () => sh[1].blocked.has('6,2'));
  t('Every order is reachable in every shift', () => sh.every((s) => s.orders.every((o) => newRun().riders.every((rd) => s.dist(rd.pos, o.rest) >= 0 && s.dist(o.rest, o.home) >= 0))));
  t('Algorithm times every order', () => sh.every((s) => runAlgo(s).times.length === s.orders.length));
  t('Algorithm average is positive', () => sh.every((s) => average(runAlgo(s).times) > 0));
  t('Verdict: lower average wins', () => verdict(10, 12) === 'win');
  t('Verdict: within 10% is close', () => verdict(13, 12) === 'close');
  t('Verdict: more than 10% slower is behind', () => verdict(14, 12) === 'behind');
  t('Losses list the biggest gaps first', () => { const l = losses([30, 20, 25, 12], [10, 10, 10, 10]); return l.length === 3 && l[0].diff === 20 && l[1].diff === 15; });
  t('BFS path length matches distance', () => { const s = sh[0], o = s.orders[0]; return s.path(o.rest, o.home).length === s.dist(o.rest, o.home) + 1; });
  t('Algorithm trace has one decision per order', () => sh.every((s) => traceAlgo(s).steps.length === s.orders.length));
  t('Orders have labels and due times', () => sh[0].orders[0].label === 'L01' && sh[0].orders[0].due === sh[0].orders[0].t + 22);
  t('Heap counts its swaps', () => { const h = new MinHeap(); [3, 2, 1].forEach((x) => h.push(x)); return h.swaps >= 2; });
  return r;
}
